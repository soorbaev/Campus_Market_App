export type Lang = 'ru' | 'en';

export function formatSom(amount: number, lang: Lang = 'ru'): string {
  const formatted = new Intl.NumberFormat('ru-RU').format(Math.round(amount));
  return lang === 'ru' ? `${formatted} сом` : `${new Intl.NumberFormat('en-US').format(Math.round(amount))} сом`;
}

export function formatSomShort(amount: number, lang: Lang = 'ru'): string {
  const formatted =
    lang === 'ru'
      ? new Intl.NumberFormat('ru-RU').format(Math.round(amount))
      : new Intl.NumberFormat('en-US').format(Math.round(amount));
  return lang === 'ru' ? `${formatted} с.` : `${formatted} сом`;
}

